"""Aggregate results/*.json into results/SUMMARY.md (markdown tables).

    python scripts/summarize.py
Reports median and mean over items per (dataset, split, separator, role).
"""
from __future__ import annotations

import json
import statistics as st
from collections import defaultdict
from pathlib import Path

BENCH = Path(__file__).resolve().parents[1]
RES = BENCH / "results"
ROLE_ORDER = ["vocals", "accompaniment", "drums", "bass", "other"]


def fmt(xs: list[float], digits: int = 2) -> str:
    xs = [x for x in xs if x is not None]
    if not xs:
        return "–"
    return f"{st.median(xs):.{digits}f} ({st.mean(xs):.{digits}f})"


def main() -> int:
    runs = [json.loads(p.read_text()) for p in sorted(RES.glob("*__*__*.json"))]
    lines = ["# Benchmark summary (generated by scripts/summarize.py)", "",
             "Cells: median (mean) over items. SDR/SI-SDR/SIR/SAR in dB, higher is better. "
             "Silent-leak in dB relative to the mixture, lower is better. "
             "RTF = processing time / audio duration (lower is faster).", ""]
    groups = defaultdict(list)
    for r in runs:
        groups[(r["dataset"], r["split"])].append(r)
    for (ds, split), rs in sorted(groups.items()):
        lines += [f"## {ds} / {split}", ""]
        first = rs[0]
        lines += [f"Items: {first['n_items']}. Holdout config sha256: "
                  f"`{first.get('frozen_config_sha256') or 'n/a (dev)'}`", ""]
        lines += ["| separator | role | SDR | SI-SDR | SIR (bleed) | SAR (artifacts) | silent-leak | n |",
                  "|---|---|---|---|---|---|---|---|"]
        for r in sorted(rs, key=lambda r: r["separator"]["id"]):
            roles = [x for x in ROLE_ORDER if x in r["items"][0]["metrics"]]
            for role in roles:
                ms = [it["metrics"][role] for it in r["items"]]
                if all(m["sdr"] is None for m in ms) and all(m["silent_leak_db"] is None for m in ms):
                    continue
                lines.append(
                    f"| {r['separator']['id']} | {role} | {fmt([m['sdr'] for m in ms])} | "
                    f"{fmt([m['si_sdr'] for m in ms])} | {fmt([m['sir'] for m in ms])} | "
                    f"{fmt([m['sar'] for m in ms])} | {fmt([m['silent_leak_db'] for m in ms], 1)} | {len(ms)} |")
        lines += ["", "| separator | RTF | model load s | peak RSS MB | peak RSS before model MB |",
                  "|---|---|---|---|---|"]
        for r in sorted(rs, key=lambda r: r["separator"]["id"]):
            lines.append(f"| {r['separator']['id']} | {fmt([it['rtf'] for it in r['items']], 3)} | "
                         f"{r['timing']['model_load_s']:.1f} | {r['memory_mb']['peak_total']:.0f} | "
                         f"{r['memory_mb']['peak_before_model']:.0f} |")
        lines.append("")
    for p in sorted(RES.glob("perf__*.json")):
        rows = json.loads(p.read_text())
        lines += [f"## Performance probe `{p.name}`", "",
                  "| separator | audio s | load s | separate s | RTF | peak RSS MB |", "|---|---|---|---|---|---|"]
        for row in rows:
            if "error" in row:
                lines.append(f"| {row['separator']} | error | | | | |")
            else:
                lines.append(f"| {row['separator']} | {row['audio_s']} | {row['load_s']:.1f} | "
                             f"{row['separate_s']:.1f} | {row['rtf']:.3f} | {row['peak_rss_mb']:.0f} |")
        lines.append("")
    (RES / "SUMMARY.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
